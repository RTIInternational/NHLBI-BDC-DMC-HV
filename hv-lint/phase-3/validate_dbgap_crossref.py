import yaml

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

# Maps directory-derived cohort name -> dbGaP cache key
COHORT_TO_CACHE_KEY: dict[str, str] = {
    "ARIC": "aric",
    "CARDIA": "cardia",
    "CHS": "chs",
    "COPDGene": "copdgene",
    "FHS": "fhs",
    "HCHS": "hchs_sol",
    "JHS": "jhs",
    "MESA": "mesa",
    "SPIROMICS": "spiromics",
    "WHI": "whi",
    "LTRC": "ltrc",
}

# Files to skip entirely (reset -- start fresh for Phase 3 restructuring)
KNOWN_ISSUES: dict[str, str] = {}

SEVERITY_RANK = {"CRITICAL": 5, "ERROR": 4, "HIGH": 3, "WARNING": 2, "INFO": 1}

# Slots that routinely reference a different table (e.g.,
# associated_participant always comes from the subject table,
# age_at_* slots reference the visit/age table).
EXPECTED_CROSS_TABLE_SLOTS = {
    "associated_participant", "associated_visit",
}
# Slot name prefixes where cross-table references are normal
EXPECTED_CROSS_TABLE_PREFIXES = (
    "age_at_", "age_of_",
)

# ---------------------------------------------------------------------------
# Accession format regexes
# ---------------------------------------------------------------------------

# Strict format: the canonical dbGaP accession pattern
PHV_STRICT_RE = re.compile(r"phv\d{8}(?!\d)")
PHT_STRICT_RE = re.compile(r"pht\d{6}(?!\d)")

# Loose format: catches anything that looks like a PHV/PHT but may have
# wrong digit count -- used by check 3.1 to detect malformed accessions
PHV_LOOSE_RE = re.compile(r"phv\d+")
PHT_LOOSE_RE = re.compile(r"pht\d+")

# ---------------------------------------------------------------------------
# Data structures
# ---------------------------------------------------------------------------

@dataclass
class Finding:
    file: str
    block: int
    check: str       # e.g., "3.1"
    severity: str    # CRITICAL, ERROR, WARNING, INFO
    message: str

    @staticmethod
    def _esc_prop(text: str) -> str:
        """Escape a workflow-command *property* value (file=, line=, ...)."""
        return (text.replace("%", "%25").replace("\r", "%0D")
                .replace("\n", "%0A").replace(":", "%3A").replace(",", "%2C"))

    @staticmethod
    def _esc_msg(text: str) -> str:
        """Escape a workflow-command *message* (colons/commas stay readable)."""
        return text.replace("%", "%25").replace("\r", "%0D").replace("\n", "%0A")

    def gh_annotation(self) -> str:
        level = {
            "CRITICAL": "error", "ERROR": "error",
            "WARNING": "warning", "HIGH": "warning", "INFO": "notice",
        }.get(self.severity, "notice")
        return f"::{level} file={self._esc_prop(self.file)}::HV-Lint [{self.check}] {self._esc_msg(self.message)} (block {self.block})"

    def terminal_line(self) -> str:
        sev = self.severity[:5].ljust(5)
        return f"  {sev}  block {self.block:>3}  [{self.check}] {self.message}"


@dataclass
class DbGaPIndex:
    """Pre-built dbGaP index for a single cohort."""
    phv_to_pht: dict[str, str] = field(default_factory=dict)  # phv -> pht
    valid_phts: set[str] = field(default_factory=set)

# ---------------------------------------------------------------------------
# Index loading
# ---------------------------------------------------------------------------

def load_dbgap_index(cache_dir: Path, cache_key: str) -> DbGaPIndex:
    """Load compressed phv->pht index for a cohort."""
    gz_path = cache_dir / f"{cache_key}.json.gz"
    json_path = cache_dir / f"{cache_key}.json"

    if gz_path.exists():
        with gzip.open(gz_path, "rt", encoding="utf-8") as f:
            mapping = json.load(f)
    elif json_path.exists():
        with json_path.open(encoding="utf-8") as f:
            mapping = json.load(f)
    else:
        raise FileNotFoundError(
            f"No dbGaP index for '{cache_key}': "
            f"expected {gz_path} or {json_path}"
        )

    idx = DbGaPIndex()
    idx.phv_to_pht = mapping
    idx.valid_phts = set(mapping.values())
    return idx

# ---------------------------------------------------------------------------
# File discovery
# ---------------------------------------------------------------------------

def find_yaml_files(base_dir: Path, cohort: str) -> list[Path]:
    files = sorted(
        f for f in base_dir.rglob("*.yaml")
        if any("-ingest" in part for part in f.parts)
        and not f.name.endswith(".swp")
    )
    if cohort.lower() != "all":
        pattern = f"{cohort}-ingest".lower()
        files = [f for f in files if pattern in str(f).lower()]
    return files


def detect_cohort(file_path: Path) -> str:
    for part in file_path.parts:
        if part.endswith("-ingest"):
            return part.replace("-ingest", "")
    return "UNKNOWN"

# ---------------------------------------------------------------------------
# Reference extraction
# ---------------------------------------------------------------------------

def extract_slot_refs(
    slot_derivs: dict, class_name: str
) -> tuple[list[tuple[str, str]], set[str]]:
    """Extract PHV references and join PHTs from slot_derivations.

    Returns:
        phv_refs: list of (phv, "slot_name on ClassName")
        join_phts: set of PHTs declared via joins
    """
    phv_refs_seen: set[tuple[str, str]] = set()
    phv_refs: list[tuple[str, str]] = []
    join_phts: set[str] = set()

    def _add_ref(phv: str, context: str) -> None:
        key = (phv, context)
        if key not in phv_refs_seen:
            phv_refs_seen.add(key)
            phv_refs.append(key)

    if not isinstance(slot_derivs, dict):
        return phv_refs, join_phts

    for slot_name, slot_def in slot_derivs.items():
        if not isinstance(slot_def, dict):
            continue

        # Direct populated_from
        pf = slot_def.get("populated_from")
        if isinstance(pf, str) and PHV_STRICT_RE.fullmatch(pf):
            _add_ref(pf, f"{slot_name} on {class_name}")

        # PHVs in expr (within {phv...} or plain references)
        expr = slot_def.get("expr")
        if isinstance(expr, str):
            for m in PHV_STRICT_RE.finditer(expr):
                _add_ref(m.group(), f"expr in {slot_name} on {class_name}")

        # PHVs in value_mappings keys
        vm = slot_def.get("value_mappings")
        if isinstance(vm, dict):
            for k in vm:
                if isinstance(k, str):
                    for m in PHV_STRICT_RE.finditer(k):
                        _add_ref(m.group(), f"value_mappings key in {slot_name} on {class_name}")

        # PHVs in expression_to_value_mappings keys
        evm = slot_def.get("expression_to_value_mappings")
        if isinstance(evm, dict):
            for k in evm:
                if isinstance(k, str):
                    for m in PHV_STRICT_RE.finditer(k):
                        _add_ref(m.group(), f"expression_to_value_mappings in {slot_name} on {class_name}")

        # Recurse into object_derivations
        od_list = slot_def.get("object_derivations") or []
        if not isinstance(od_list, list):
            od_list = []
        for od in od_list:
            if isinstance(od, dict) and "class_derivations" in od:
                nested_cd = od["class_derivations"]
                if not isinstance(nested_cd, dict):
                    continue
                for nested_cls, nested_def in nested_cd.items():
                    if isinstance(nested_def, dict):
                        nested_slots = nested_def.get("slot_derivations")
                        nested_slots = nested_slots if isinstance(nested_slots, dict) else {}
                        nested_phvs, nested_joins = extract_slot_refs(nested_slots, nested_cls)
                        for ref in nested_phvs:
                            if ref not in phv_refs_seen:
                                phv_refs_seen.add(ref)
                                phv_refs.append(ref)
                        join_phts.update(nested_joins)

                        # Nested class populated_from PHT
                        npht = nested_def.get("populated_from")
                        if isinstance(npht, str) and PHT_STRICT_RE.fullmatch(npht):
                            join_phts.add(npht)

    return phv_refs, join_phts


# ---------------------------------------------------------------------------
# Check 3.1: Accession format validation
# ---------------------------------------------------------------------------

def _collect_accession_strings(block: dict) -> list[tuple[str, str]]:
    """Collect all string values that look like PHV/PHT accessions.

    Returns list of (accession_string, context_description).
    Uses loose regex to catch malformed accessions that the strict
    regex would silently skip.
    """
    results: list[tuple[str, str]] = []
    class_derivs = block.get("class_derivations")
    if not isinstance(class_derivs, dict):
        return results

    for class_name, class_def in class_derivs.items():
        if not isinstance(class_def, dict):
            continue

        # Class populated_from (PHT)
        pf = class_def.get("populated_from")
        if isinstance(pf, str):
            for m in PHT_LOOSE_RE.finditer(pf):
                results.append((m.group(), f"populated_from on {class_name}"))
            for m in PHV_LOOSE_RE.finditer(pf):
                results.append((m.group(), f"populated_from on {class_name}"))

        # Joins populated_from (PHT)
        raw_joins = class_def.get("joins")
        if isinstance(raw_joins, list):
            for j in raw_joins:
                if isinstance(j, dict):
                    jpf = j.get("populated_from")
                    if isinstance(jpf, str):
                        for m in PHT_LOOSE_RE.finditer(jpf):
                            results.append((m.group(), f"joins on {class_name}"))

        # Walk slot_derivations
        slot_derivs = class_def.get("slot_derivations")
        if isinstance(slot_derivs, dict):
            results.extend(_collect_slot_accessions(slot_derivs, class_name))

    return results


def _collect_slot_accessions(
    slot_derivs: dict, class_name: str
) -> list[tuple[str, str]]:
    """Collect accession-like strings from slot_derivations."""
    results: list[tuple[str, str]] = []
    for slot_name, slot_def in slot_derivs.items():
        if not isinstance(slot_def, dict):
            continue

        pf = slot_def.get("populated_from")
        if isinstance(pf, str):
            for m in PHV_LOOSE_RE.finditer(pf):
                results.append((m.group(), f"{slot_name} on {class_name}"))

        expr = slot_def.get("expr")
        if isinstance(expr, str):
            for m in PHV_LOOSE_RE.finditer(expr):
                results.append((m.group(), f"expr in {slot_name} on {class_name}"))

        for key_name in ("value_mappings", "expression_to_value_mappings"):
            mapping = slot_def.get(key_name)
            if isinstance(mapping, dict):
                for k in mapping:
                    if isinstance(k, str):
                        for m in PHV_LOOSE_RE.finditer(k):
                            results.append((m.group(), f"{key_name} in {slot_name} on {class_name}"))

        # Recurse into object_derivations
        od_list = slot_def.get("object_derivations") or []
        if not isinstance(od_list, list):
            od_list = []
        for od in od_list:
            if isinstance(od, dict) and "class_derivations" in od:
                nested_cd = od["class_derivations"]
                if isinstance(nested_cd, dict):
                    for nested_cls, nested_def in nested_cd.items():
                        if isinstance(nested_def, dict):
                            npf = nested_def.get("populated_from")
                            if isinstance(npf, str):
                                for m in PHT_LOOSE_RE.finditer(npf):
                                    results.append((m.group(), f"nested populated_from on {nested_cls}"))
                            nested_slots = nested_def.get("slot_derivations")
                            if isinstance(nested_slots, dict):
                                results.extend(_collect_slot_accessions(nested_slots, nested_cls))
    return results


def check_accession_format(
    block: dict, block_idx: int, rel_path: str
) -> list[Finding]:
    """Check 3.1: Flag accession strings that don't match canonical format."""
    findings: list[Finding] = []
    seen: set[tuple[str, str]] = set()

    for accession, context in _collect_accession_strings(block):
        key = (accession, context)
        if key in seen:
            continue
        seen.add(key)

        if accession.startswith("phv"):
            if not PHV_STRICT_RE.fullmatch(accession):
                findings.append(Finding(
                    rel_path, block_idx, "3.1", "ERROR",
                    f"Malformed PHV '{accession}' ({context}) -- "
                    f"expected phv + exactly 8 digits"
                ))
        elif accession.startswith("pht"):
            if not PHT_STRICT_RE.fullmatch(accession):
                findings.append(Finding(
                    rel_path, block_idx, "3.1", "ERROR",
                    f"Malformed PHT '{accession}' ({context}) -- "
                    f"expected pht + exactly 6 digits"
                ))

    return findings


# ---------------------------------------------------------------------------
# Checks 3.2-3.5
# ---------------------------------------------------------------------------

def check_block(
    block: dict, block_idx: int, rel_path: str,
    dbgap: DbGaPIndex
) -> list[Finding]:
    """Run checks 3.2-3.5 on a single block."""
    findings: list[Finding] = []
    class_derivs = block.get("class_derivations")
    if not isinstance(class_derivs, dict):
        return findings

    for class_name, class_def in class_derivs.items():
        if not isinstance(class_def, dict):
            continue

        raw_pht = class_def.get("populated_from", "")
        class_pht = raw_pht if isinstance(raw_pht, str) and PHT_STRICT_RE.fullmatch(raw_pht) else ""
        raw_joins = class_def.get("joins")
        has_joins = isinstance(raw_joins, list)
        if raw_joins is not None and not has_joins:
            findings.append(Finding(
                rel_path, block_idx, "3.0", "ERROR",
                f"{class_name} joins is "
                f"{type(raw_joins).__name__}, expected list"
            ))
        slot_derivs = class_def.get("slot_derivations")
        if not isinstance(slot_derivs, dict):
            if slot_derivs is not None:
                findings.append(Finding(
                    rel_path, block_idx, "3.0", "ERROR",
                    f"{class_name} slot_derivations is "
                    f"{type(slot_derivs).__name__}, expected mapping"
                ))
            slot_derivs = {}

        # Collect join PHTs for cross-table detection
        join_phts: set[str] = set()
        if has_joins:
            for j in class_def["joins"]:
                if isinstance(j, dict):
                    jpht = j.get("populated_from", "")
                    if isinstance(jpht, str) and PHT_STRICT_RE.fullmatch(jpht):
                        join_phts.add(jpht)

        # -- Check 3.2: PHT existence --
        if class_pht and class_pht not in dbgap.valid_phts:
            findings.append(Finding(
                rel_path, block_idx, "3.2", "ERROR",
                f"PHT '{class_pht}' on {class_name} not found in "
                f"dbGaP variable index"
            ))

        # Extract PHV references from slot derivations
        phv_refs, nested_join_phts = extract_slot_refs(slot_derivs, class_name)
        join_phts.update(nested_join_phts)

        # Track which non-class PHTs are reachable via joins
        all_reachable_phts = ({class_pht} if class_pht else set()) | join_phts

        for phv, context in phv_refs:
            # -- Check 3.3: PHV existence --
            if phv not in dbgap.phv_to_pht:
                findings.append(Finding(
                    rel_path, block_idx, "3.3", "ERROR",
                    f"PHV '{phv}' ({context}) not found in dbGaP index"
                ))
                continue

            actual_pht = dbgap.phv_to_pht[phv]

            # -- Check 3.4 / 3.5: PHV-to-PHT membership --
            if not class_pht:
                continue
            if actual_pht != class_pht:
                # Determine the slot name from context string
                slot_in_context = context.split(" on ")[0] if " on " in context else ""
                # For "expr in slot_name" patterns, extract the actual slot
                bare_slot = slot_in_context.replace("expr in ", "").replace(
                    "value_mappings key in ", ""
                ).replace("expression_to_value_mappings in ", "")

                if actual_pht in all_reachable_phts:
                    # Cross-table but covered by a join
                    findings.append(Finding(
                        rel_path, block_idx, "3.4", "INFO",
                        f"PHV '{phv}' ({context}) belongs to {actual_pht}, "
                        f"not class PHT {class_pht} (covered by joins)"
                    ))
                elif (bare_slot in EXPECTED_CROSS_TABLE_SLOTS
                      or any(bare_slot.startswith(pfx) for pfx in EXPECTED_CROSS_TABLE_PREFIXES)):
                    # Expected cross-table pattern
                    findings.append(Finding(
                        rel_path, block_idx, "3.4", "INFO",
                        f"PHV '{phv}' ({context}) belongs to {actual_pht}, "
                        f"not class PHT {class_pht} (expected cross-table)"
                    ))
                else:
                    # Unexpected cross-table reference
                    findings.append(Finding(
                        rel_path, block_idx, "3.5", "WARNING",
                        f"PHV '{phv}' ({context}) belongs to {actual_pht}, "
                        f"not class PHT {class_pht} - possible cross-table "
                        f"reference without joins"
                    ))

    return findings


