#!/usr/bin/env python3
"""HV-Lint Phase 3: dbGaP cross-reference validation for HV YAML files.

Validates that PHV and PHT accessions referenced in transformation YAML
files actually exist in the dbGaP variable index and have correct
table membership.

Requires a pre-built compressed index (generated by build_phv_index.py).

Usage:
    python hv-lint/phase-3/validate_dbgap_crossref.py --cache-dir hv-lint/dbgap-cache
    python hv-lint/phase-3/validate_dbgap_crossref.py --cache-dir hv-lint/dbgap-cache --cohort ARIC

Checks implemented:
    3.1  PHV/PHT accession format -- malformed accessions flagged
    3.2  PHT existence -- referenced PHTs must exist in dbGaP index
    3.3  PHV existence -- referenced PHVs must exist in dbGaP index
    3.4  PHV-to-PHT membership -- PHVs must belong to the declared table
    3.5  Cross-table reference -- PHV from a different table without joins
"""

from __future__ import annotations

