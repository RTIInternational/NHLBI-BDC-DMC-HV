def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="HV-Lint Phase 3: Semantic validation (3.9, 3.10, 3.12-3.16)"
    )
    p.add_argument(
        "--cache-dir", required=True,
        help="Directory containing per-cohort *_detail.json.gz indexes"
    )
    p.add_argument(
        "--cohort", default="all",
        help="Cohort to validate or 'all' (default: all)"
    )
    p.add_argument(
        "--expect-study", default=None,
        help="OVERRIDE the release the cohort declares (phs000287 or phs000287.v7). The check "
             "always runs: without this flag the expectation comes from the cohort's "
             "_manifest-<cohort>.yaml, and a cache with no recorded provenance fails it.",
    )
    p.add_argument(
        "--fail-on", default="error",
        choices=["critical", "error", "high", "warning", "info"],
        help="Minimum severity for non-zero exit (default: error)"
    )
    p.add_argument(
        "--check", nargs="*", default=None,
        choices=["3.9", "3.10", "3.12", "3.13", "3.14", "3.15", "3.16"],
        help="Run only specific checks (default: all)"
    )
    return p.parse_args()


def main() -> int:
    args = parse_args()
    in_ci = os.environ.get("GITHUB_ACTIONS") == "true"
    cache_dir = Path(args.cache_dir)
    enabled_checks = set(args.check) if args.check else {"3.9", "3.10", "3.12", "3.13", "3.14", "3.15", "3.16"}

    if not cache_dir.is_dir():
        print(f"ERROR: Cache directory not found: {cache_dir}", file=sys.stderr)
        print("Run build_phv_detail_index.py first.", file=sys.stderr)
        return 1

    # Load detail indexes
    indexes: dict[str, DetailIndex] = {}
    stats_by_cohort: dict[str, dict | None] = {}
    pairs = _cohorts.cohorts_to_load(args.cohort, cache_dir, find_transform_dir())
    missing: list[tuple[str, str]] = []
    for cohort_name, cache_key in pairs:
        try:
            indexes[cohort_name] = load_detail_index(cache_dir, cache_key)
            stats_by_cohort[cohort_name] = _css.load_stats_index(cache_dir, cache_key)
            if stats_by_cohort[cohort_name] is None:
                print(f"ERROR: no {cache_key}_stats.json.gz for {cohort_name}: 3.9 / 3.15 "
                      f"compare against observed values and cannot run without it.",
                      file=sys.stderr)
                return 1
            count = len(indexes[cohort_name].records)
            coded = sum(1 for r in indexes[cohort_name].records.values() if r.codes)
            print(f"  Loaded {cohort_name}: {count:,} PHVs ({coded:,} coded) "
                  f"[{_cohorts.study_label(cache_dir, cache_key)}]")
            # The release being linted against is ALWAYS checked, never assumed. `--expect-study`
            # overrides; otherwise the cohort's own declaration in
            # hv_dataqc/cache_fetcher/manifests/_manifest-<cohort>.yaml is the expectation. A
            # cohort that declares nothing is a hard failure, because "lint against whichever
            # cache happens to be present" is how a superseded release goes unnoticed.
            expected = args.expect_study or _cohorts.declared_study(cohort_name, cache_dir=cache_dir)
            if not expected:
                print(
                    f"ERROR: cohort '{cohort_name}' declares no dbGaP release, so the cache "
                    f"cannot be checked. Add hv_dataqc/cache_fetcher/manifests/"
                    f"_manifest-<cohort>.yaml with current_version.study_id and data_version, "
                    f"or pass --expect-study phs######.v#.",
                    file=sys.stderr,
                )
                return 1
            source = "--expect-study" if args.expect_study else "declared release"
            mismatch = _cohorts.study_mismatch(cache_dir, cache_key, expected)
            if mismatch:
                print(f"ERROR: study version check ({source} {expected}): {mismatch}",
                      file=sys.stderr)
                return 1
        except FileNotFoundError:
            missing.append((cohort_name, cache_key))

    # A cache the run asked for and did not get is a HARD failure naming what it looked for.
    # Previously an unresolvable cohort produced an empty dict and the generic message "No dbGaP
    # indexes found. Run build_phv_index.py." -- which names the wrong remedy when the cache is
    # present but the cohort was simply not on the list, and cannot say WHICH cohort failed.
    if missing:
        for cohort_name, cache_key in missing:
            print(
                f"ERROR: no dbGaP index for cohort '{cohort_name}' -- looked for "
                f"'{cache_key}.json.gz' in {cache_dir}. Build it with build_phv_index.py "
                f"and build_phv_detail_index.py (--source-cache <dbgap staging dir>).",
                file=sys.stderr,
            )
        return 1

    # Discover YAML files
    base_dir = find_transform_dir()
    hv_root = base_dir.parent
    yaml_files = find_yaml_files(base_dir, args.cohort)
    if not yaml_files:
        print(f"No YAML files found under {base_dir}")
        return 0

    print(f"Found {len(yaml_files)} YAML files to validate")
    print(f"Enabled checks: {', '.join(sorted(enabled_checks))}")

    # Run checks
    all_findings: list[Finding] = []
    followup_idx: dict[str, object] = {}
    files_checked = 0
    blocks_checked = 0

    for file_path in yaml_files:
        rel_path = file_path.relative_to(hv_root).as_posix()

        cohort = detect_cohort(file_path)
        if cohort not in indexes:
            continue

        try:
            with file_path.open(encoding="utf-8") as f:
                data = yaml.safe_load(f)
        except (OSError, yaml.YAMLError):
            continue

        if data is None:
            continue

        blocks = data if isinstance(data, list) else [data]
        files_checked += 1
        detail_idx = indexes[cohort]
        stats = stats_by_cohort.get(cohort)
        if cohort not in followup_idx:
            followup_idx[cohort] = _css.DetailIndex.from_records(detail_idx.records)

        # Pre-compute file domain for 3.12
        file_domain = _filename_domain_keywords(file_path.name)

        for idx, block in enumerate(blocks):
            blocks_checked += 1
            if not isinstance(block, dict):
                continue

            if "3.9" in enabled_checks:
                all_findings.extend(
                    check_value_mappings_completeness(
                        block, idx, rel_path, detail_idx, stats, followup_idx[cohort]
                    )
                )
            if "3.10" in enabled_checks:
                all_findings.extend(
                    check_phv_type_compatibility(
                        block, idx, rel_path, detail_idx
                    )
                )
            if "3.12" in enabled_checks:
                all_findings.extend(
                    check_phv_domain_mismatch(
                        block, idx, rel_path, detail_idx, file_domain
                    )
                )
            if "3.13" in enabled_checks:
                all_findings.extend(
                    check_condition_null_default(
                        block, idx, rel_path, detail_idx
                    )
                )
            if "3.14" in enabled_checks:
                all_findings.extend(
                    check_unit_conversion_mismatch(
                        block, idx, rel_path, detail_idx
                    )
                )
            if "3.15" in enabled_checks:
                all_findings.extend(
                    check_phantom_codes(
                        block, idx, rel_path, detail_idx, stats
                    )
                )
            if "3.16" in enabled_checks:
                all_findings.extend(
                    check_quantity_missing_unit(
                        block, idx, rel_path,
                    )
                )

    # Report
    # Known issues, stale entries and the WARNING ratchet (hv-lint/_known_issues.py).
    all_findings.extend(_known_issues.finalize(
        all_findings, checks=enabled_checks, scanned_files=yaml_files, make_finding=Finding))

    fail_rank = SEVERITY_RANK[args.fail_on.upper()]

    counts: dict[str, int] = {}
    for f in all_findings:
        counts[f.severity] = counts.get(f.severity, 0) + 1

    findings_by_file: dict[str, list[Finding]] = {}
    for f in all_findings:
        findings_by_file.setdefault(f.file, []).append(f)

    print(f"\n{'='*70}")
    print("HV-Lint Phase 3: Semantic Validation Results")
    print(f"{'='*70}")
    print(f"Files checked:  {files_checked}")
    print(f"Blocks checked: {blocks_checked}")

    parts = []
    for sev in ("CRITICAL", "ERROR", "HIGH", "WARNING", "INFO"):
        if counts.get(sev, 0) > 0:
            parts.append(f"{counts[sev]} {sev}")
    if parts:
        print(f"Findings:       {', '.join(parts)}")
    else:
        print("Findings:       None -- all semantic checks passed!")

    if findings_by_file:
        print(f"\n{'-'*70}")
        for fpath in sorted(findings_by_file):
            short = fpath.replace("priority_variables_transform/", "")
            print(f"\n{short}:")
            for f in sorted(findings_by_file[fpath], key=lambda x: (x.block, x.check)):
                print(f.terminal_line())
                if in_ci:
                    print(f.gh_annotation())

    blocking = [
        f for f in all_findings
        if SEVERITY_RANK.get(f.severity, 0) >= fail_rank
    ]
    if blocking:
        print(f"\nFAILED: {len(blocking)} findings at or above '{args.fail_on}'")
        return 1
    if all_findings:
        print(f"\nPASSED (with {len(all_findings)} advisory findings below fail threshold)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
