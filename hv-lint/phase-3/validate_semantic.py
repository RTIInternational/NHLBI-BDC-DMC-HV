# ---------------------------------------------------------------------------
# Check 3.9: value_mappings Completeness
# ---------------------------------------------------------------------------


def check_value_mappings_completeness(
    block: dict, block_idx: int, rel_path: str,
    detail_idx: DetailIndex,
) -> list[Finding]:
    """Check 3.9: Flag dbGaP coded values absent from value_mappings."""
    findings: list[Finding] = []
    class_derivs = block.get("class_derivations")
    if not isinstance(class_derivs, dict):
        return findings

    for cls_name, cls_def in class_derivs.items():
        if not isinstance(cls_def, dict):
            continue
        slot_derivs = cls_def.get("slot_derivations")
        if not isinstance(slot_derivs, dict):
            continue
        class_pht = cls_def.get("populated_from", "")

        for slot_name, slot_def in slot_derivs.items():
            if not isinstance(slot_def, dict):
                continue

            # Only check slots that use value_mappings as the sole mechanism
            vm = slot_def.get("value_mappings")
            if not isinstance(vm, dict) or not vm:
                continue

            # Skip if there's also an expr (expr may handle additional logic)
            if slot_def.get("expr"):
                continue

            # Determine source PHV
            pf = slot_def.get("populated_from")
            if not isinstance(pf, str) or not PHV_RE.fullmatch(pf):
                continue

            detail = detail_idx.records.get(pf)
            if not detail or not detail.codes:
                continue

            # Compare: dbGaP codes vs value_mappings keys
            dbgap_codes = set(detail.codes.keys())
            yaml_codes = set(str(k) for k in vm.keys())

            missing = dbgap_codes - yaml_codes
            if not missing:
                continue

            for code in sorted(missing):
                label = detail.codes.get(code, "")
                if SKIP_LABEL_RE.search(label):
                    # Known skip pattern -- downgrade to INFO
                    findings.append(Finding(
                        file=rel_path,
                        block=block_idx,
                        check="3.9",
                        severity="INFO",
                        message=(
                            f"value_mappings on {cls_name}.{slot_name} "
                            f"({pf}) missing dbGaP code '{code}' "
                            f"(\"{label}\") -- likely intentional skip"
                        ),
                    ))
                else:
                    sev = "ERROR" if slot_name in HIGH_IMPACT_SLOTS else "WARNING"
                    findings.append(Finding(
                        file=rel_path,
                        block=block_idx,
                        check="3.9",
                        severity=sev,
                        message=(
                            f"value_mappings on {cls_name}.{slot_name} "
                            f"({pf}) missing dbGaP code '{code}' "
                            f"(\"{label}\") -- possible data loss"
                        ),
                    ))

    return findings


# ---------------------------------------------------------------------------
# Check 3.10: PHV Type <-> Slot Role Compatibility
# ---------------------------------------------------------------------------


def check_phv_type_compatibility(
    block: dict, block_idx: int, rel_path: str,
    detail_idx: DetailIndex,
) -> list[Finding]:
    """Check 3.10: Flag PHVs whose dbGaP type conflicts with slot role."""
    findings: list[Finding] = []
    class_derivs = block.get("class_derivations")
    if not isinstance(class_derivs, dict):
        return findings

    for cls_name, cls_def in class_derivs.items():
        if not isinstance(cls_def, dict):
            continue
        slot_derivs = cls_def.get("slot_derivations")
        if not isinstance(slot_derivs, dict):
            continue

        for slot_name, slot_def in slot_derivs.items():
            if not isinstance(slot_def, dict):
                continue

            # Only check bare populated_from (no expr wrapping)
            pf = slot_def.get("populated_from")
            if not isinstance(pf, str) or not PHV_RE.fullmatch(pf):
                continue
            # Skip if expr is present -- the expression handles conversion
            if slot_def.get("expr"):
                continue
            # Skip if value_mappings -- the mappings handle type conversion
            if slot_def.get("value_mappings"):
                continue

            detail = detail_idx.records.get(pf)
            if not detail:
                continue

            vtype = detail.type.lower()  # e.g., "encoded value", "decimal", "integer"
            unit = (detail.unit or "").lower()

            # Check enum slots fed by numeric types
            if slot_name in ENUM_SLOTS:
                if vtype in ("decimal", "integer", "num"):
                    suggestion = _suggest_adjacent(
                        detail_idx, detail.pht, detail.name,
                        {"encoded value", "encoded"},
                    )
                    msg = (
                        f"{cls_name}.{slot_name} populated_from "
                        f"{pf} ({detail.name}) has type '{detail.type}'"
                    )
                    if "day" in unit:
                        msg += f" with unit '{detail.unit}'"
                    msg += " -- expected 'encoded value' for this slot"
                    if suggestion:
                        msg += f". Did you mean {suggestion}?"
                    findings.append(Finding(
                        file=rel_path,
                        block=block_idx,
                        check="3.10",
                        severity="ERROR",
                        message=msg,
                    ))

            # Check numeric slots fed by encoded types
            if slot_name in NUMERIC_SLOTS:
                if vtype in ("encoded value", "encoded"):
                    suggestion = _suggest_adjacent(
                        detail_idx, detail.pht, detail.name,
                        {"decimal", "integer", "num"},
                    )
                    msg = (
                        f"{cls_name}.{slot_name} populated_from "
                        f"{pf} ({detail.name}) has type '{detail.type}'"
                        f" -- expected numeric type for this slot"
                    )
                    if suggestion:
                        msg += f". Did you mean {suggestion}?"
                    findings.append(Finding(
                        file=rel_path,
                        block=block_idx,
                        check="3.10",
                        severity="ERROR",
                        message=msg,
                    ))

    return findings


def _suggest_adjacent(
    detail_idx: DetailIndex, pht: str, var_name: str,
    compatible_types: set[str],
) -> str | None:
    """Search for a nearby PHV in the same PHT with a compatible type.

    Looks for variables with a name that shares a prefix with the target.
    """
    if not pht or not var_name:
        return None

    # Extract a prefix to match against (first chars before trailing digits)
    prefix = re.sub(r"\d+$", "", var_name)
    if len(prefix) < 2:
        return None

    candidates = []
    for phv, rec in detail_idx.records.items():
        if rec.pht != pht:
            continue
        if rec.name == var_name:
            continue
        if rec.type.lower() not in compatible_types:
            continue
        if rec.name.startswith(prefix):
            candidates.append((phv, rec.name))

    if not candidates:
        return None

    # Return the best match (shortest name difference)
    candidates.sort(key=lambda x: abs(len(x[1]) - len(var_name)))
    phv, name = candidates[0]
    return f"{phv} ({name}, type: {detail_idx.records[phv].type})"


# ---------------------------------------------------------------------------
# Check 3.12: PHV Description <-> Domain Mismatch
# ---------------------------------------------------------------------------


def check_phv_domain_mismatch(
    block: dict, block_idx: int, rel_path: str,
    detail_idx: DetailIndex,
    file_domain: set[str],
) -> list[Finding]:
    """Check 3.12: Flag PHVs whose description conflicts with file domain."""
    findings: list[Finding] = []
    if not file_domain:
        return findings

    class_derivs = block.get("class_derivations")
    if not isinstance(class_derivs, dict):
        return findings

    for cls_name, cls_def in class_derivs.items():
        if not isinstance(cls_def, dict):
            continue
        slot_derivs = cls_def.get("slot_derivations")
        if not isinstance(slot_derivs, dict):
            continue

        for slot_name, slot_def in slot_derivs.items():
            if not isinstance(slot_def, dict):
                continue

            # Collect all PHV refs in this slot
            phvs: list[str] = []
            pf = slot_def.get("populated_from")
            if isinstance(pf, str) and PHV_RE.fullmatch(pf):
                phvs.append(pf)
            expr = slot_def.get("expr")
            if isinstance(expr, str):
                phvs.extend(m.group() for m in PHV_RE.finditer(expr))

            for phv in phvs:
                detail = detail_idx.records.get(phv)
                if not detail:
                    continue

                desc_lower = detail.description.lower()
                desc_words = set(re.findall(r"[a-z]+", desc_lower))

                for domain_a, conflict_b in DOMAIN_CONFLICTS:
                    # Check if file domain overlaps with domain_a
                    if not (file_domain & domain_a):
                        continue
                    # Check if PHV description contains conflict_b terms
                    matched_conflicts = desc_words & conflict_b
                    # Also check multi-word conflict terms
                    for term in conflict_b:
                        if " " in term and term in desc_lower:
                            matched_conflicts.add(term)

                    if matched_conflicts:
                        findings.append(Finding(
                            file=rel_path,
                            block=block_idx,
                            check="3.12",
                            severity="WARNING",
                            message=(
                                f"{cls_name}.{slot_name}: {phv} "
                                f"({detail.name}) description "
                                f"\"{detail.description[:80]}\" contains "
                                f"domain keyword(s) "
                                f"{sorted(matched_conflicts)} -- "
                                f"conflicts with file domain "
                                f"{sorted(file_domain & domain_a)}"
                            ),
                        ))
                        break  # One conflict per PHV is enough

    return findings


