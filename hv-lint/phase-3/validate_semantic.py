#!/usr/bin/env python3
"""HV-Lint Phase 3: Semantic validation using extended PHV detail index.

Validates that YAML transformation files are semantically consistent
with the dbGaP FTP data dictionaries. Requires the extended detail
index generated by build_phv_detail_index.py.

Checks:
    3.9   value_mappings completeness -- source codes in dbGaP but absent
          from value_mappings are flagged (silent data loss)
    3.10  PHV type vs slot role, at any depth -- an enum slot (status, sex, race, ...) fed by a
          bare variable with no value_mappings; a numeric slot fed by a variable with category
          codes
    3.12  PHV description vs concept domain -- variable description keywords
          should not conflict with the file's clinical domain
    3.13  Condition null-default risk -- Condition blocks whose visit case
          routes to phases where condition_status PHV is not collected
          (null -> false ABSENT)
    3.14  unit_conversion source_unit mismatch -- unit_conversion source_unit
          must match the dbGaP-declared unit for the source PHV
    3.15  Phantom code detection -- value_mappings keys that don't exist in
          dbGaP coded values (typo, cross-cohort copy-paste, version drift)
    3.16  Quantity missing unit -- a measured value (value_decimal / value_integer) with no
          unit, at any depth (ERROR; UNITLESS_OBSERVATION_TYPES is the allowlist)

Usage:
    python hv-lint/phase-3/validate_semantic.py --cache-dir hv-lint/dbgap-cache
    python hv-lint/phase-3/validate_semantic.py --cache-dir hv-lint/dbgap-cache --cohort HCHS
"""

