def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="HV-Lint Phase 3: Semantic validation (3.9, 3.10, 3.12-3.16)"
    )
    p.add_argument(
        "--cache-dir", required=True,
        help="Directory containing per-cohort *_detail.json.gz indexes"
    )
    p.add_argument(
        "--cohort", default="all",
        help="Cohort to validate or 'all' (default: all)"
    )
    p.add_argument(
        "--fail-on", default="error",
        choices=["critical", "error", "high", "warning", "info"],
        help="Minimum severity for non-zero exit (default: error)"
    )
    p.add_argument(
        "--check", nargs="*", default=None,
        choices=["3.9", "3.10", "3.12", "3.13", "3.14", "3.15", "3.16"],
        help="Run only specific checks (default: all)"
    )
    return p.parse_args()


def main() -> int:
    args = parse_args()
    in_ci = os.environ.get("GITHUB_ACTIONS") == "true"
    cache_dir = Path(args.cache_dir)
    enabled_checks = set(args.check) if args.check else {"3.9", "3.10", "3.12", "3.13", "3.14", "3.15", "3.16"}

    if not cache_dir.is_dir():
        print(f"ERROR: Cache directory not found: {cache_dir}", file=sys.stderr)
        print("Run build_phv_detail_index.py first.", file=sys.stderr)
        return 1

    # Load detail indexes
    indexes: dict[str, DetailIndex] = {}
    cohort_upper = args.cohort.upper()
    needed = (
        {k: v for k, v in COHORT_TO_CACHE_KEY.items() if k.upper() == cohort_upper}
        if cohort_upper != "ALL"
        else COHORT_TO_CACHE_KEY
    )
    for cohort_name, cache_key in needed.items():
        try:
            indexes[cohort_name] = load_detail_index(cache_dir, cache_key)
            count = len(indexes[cohort_name].records)
            coded = sum(1 for r in indexes[cohort_name].records.values() if r.codes)
            print(f"  Loaded {cohort_name}: {count:,} PHVs ({coded:,} coded)")
        except FileNotFoundError:
            pass

    if not indexes:
        print("ERROR: No detail indexes found. Run build_phv_detail_index.py.",
              file=sys.stderr)
        return 1

    # Discover YAML files
    base_dir = find_transform_dir()
    hv_root = base_dir.parent
    yaml_files = find_yaml_files(base_dir, args.cohort)
    if not yaml_files:
        print(f"No YAML files found under {base_dir}")
        return 0

    print(f"Found {len(yaml_files)} YAML files to validate")
    print(f"Enabled checks: {', '.join(sorted(enabled_checks))}")

    # Run checks
    all_findings: list[Finding] = []
    files_checked = 0
    blocks_checked = 0

    for file_path in yaml_files:
        rel_path = file_path.relative_to(hv_root).as_posix()

        cohort = detect_cohort(file_path)
        if cohort not in indexes:
            continue

        try:
            with file_path.open(encoding="utf-8") as f:
                data = yaml.safe_load(f)
        except (OSError, yaml.YAMLError):
            continue

        if data is None:
            continue

        blocks = data if isinstance(data, list) else [data]
        files_checked += 1
        detail_idx = indexes[cohort]

        # Pre-compute file domain for 3.12
        file_domain = _filename_domain_keywords(file_path.name)

        for idx, block in enumerate(blocks):
            blocks_checked += 1
            if not isinstance(block, dict):
                continue

            if "3.9" in enabled_checks:
                all_findings.extend(
                    check_value_mappings_completeness(
                        block, idx, rel_path, detail_idx
                    )
                )
            if "3.10" in enabled_checks:
                all_findings.extend(
                    check_phv_type_compatibility(
                        block, idx, rel_path, detail_idx
                    )
                )
            if "3.12" in enabled_checks:
                all_findings.extend(
                    check_phv_domain_mismatch(
                        block, idx, rel_path, detail_idx, file_domain
                    )
                )
            if "3.13" in enabled_checks:
                all_findings.extend(
                    check_condition_null_default(
                        block, idx, rel_path, detail_idx
                    )
                )
            if "3.14" in enabled_checks:
                all_findings.extend(
                    check_unit_conversion_mismatch(
                        block, idx, rel_path, detail_idx
                    )
                )
            if "3.15" in enabled_checks:
                all_findings.extend(
                    check_phantom_codes(
                        block, idx, rel_path, detail_idx
                    )
                )
            if "3.16" in enabled_checks:
                all_findings.extend(
                    check_quantity_missing_unit(
                        block, idx, rel_path,
                    )
                )

    # Report
    fail_rank = SEVERITY_RANK[args.fail_on.upper()]

    counts: dict[str, int] = {}
    for f in all_findings:
        counts[f.severity] = counts.get(f.severity, 0) + 1

    findings_by_file: dict[str, list[Finding]] = {}
    for f in all_findings:
        findings_by_file.setdefault(f.file, []).append(f)

    print(f"\n{'='*70}")
    print("HV-Lint Phase 3: Semantic Validation Results")
    print(f"{'='*70}")
    print(f"Files checked:  {files_checked}")
    print(f"Blocks checked: {blocks_checked}")

    parts = []
    for sev in ("CRITICAL", "ERROR", "HIGH", "WARNING", "INFO"):
        if counts.get(sev, 0) > 0:
            parts.append(f"{counts[sev]} {sev}")
    if parts:
        print(f"Findings:       {', '.join(parts)}")
    else:
        print("Findings:       None -- all semantic checks passed!")

    if findings_by_file:
        print(f"\n{'-'*70}")
        for fpath in sorted(findings_by_file):
            short = fpath.replace("priority_variables_transform/", "")
            print(f"\n{short}:")
            for f in sorted(findings_by_file[fpath], key=lambda x: (x.block, x.check)):
                print(f.terminal_line())
                if in_ci:
                    print(f.gh_annotation())

    blocking = [
        f for f in all_findings
        if SEVERITY_RANK.get(f.severity, 0) >= fail_rank
    ]
    if blocking:
        print(f"\nFAILED: {len(blocking)} findings at or above '{args.fail_on}'")
        return 1
    if all_findings:
        print(f"\nPASSED (with {len(all_findings)} advisory findings below fail threshold)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
