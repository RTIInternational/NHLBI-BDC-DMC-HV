# Check 3.16: Quantity Missing Unit
# ---------------------------------------------------------------------------


#: observation_type CURIEs whose value is genuinely dimensionless, so a Quantity without a unit is
#: correct. Empty: every measured value on main has a unit. A dimensionless value can instead carry
#: the UCUM unit "1".
UNITLESS_OBSERVATION_TYPES: dict[str, str] = {}


def check_quantity_missing_unit(
    block: dict, block_idx: int, rel_path: str,
) -> list[Finding]:
    """Check 3.16: a measured value (Quantity value_decimal / value_integer) with no unit (ERROR).

    Walks every depth (a Quantity inside a MeasurementObservation inside a Set included). The
    value of a Quantity without a unit cannot be interpreted downstream, and a block that
    converts the value (``* 38.67``) without stating the unit is a silent scale error.
    """
    findings: list[Finding] = []

    def visit(cls_name: str, cls_def: dict, where: str, obs_type: str | None) -> None:
        slots = cls_def.get("slot_derivations")
        if not isinstance(slots, dict):
            return
        ot = slots.get("observation_type")
        if isinstance(ot, dict) and isinstance(ot.get("value"), str):
            obs_type = ot["value"]
        if cls_name == "Quantity":
            numeric = next((n for n in ("value_decimal", "value_integer") if n in slots), None)
            if numeric and "unit" not in slots and obs_type not in UNITLESS_OBSERVATION_TYPES:
                findings.append(Finding(
                    file=rel_path, block=block_idx, check="3.16", severity="ERROR",
                    message=(
                        f"Quantity{(' (in ' + where + ')') if where else ''} has {numeric} but "
                        f"no unit (observation_type {obs_type or 'none'}) -- the measured value "
                        f"cannot be interpreted. Add the unit, or '1' for a dimensionless value"
                    ),
                ))
        for slot_name, slot_def in slots.items():
            if isinstance(slot_def, dict):
                for ncls, ndef in iter_nested_class_derivs(slot_def):
                    if isinstance(ndef, dict):
                        visit(ncls, ndef, f"{where + '.' if where else ''}{cls_name}.{slot_name}",
                              obs_type)

    class_derivs = block.get("class_derivations")
    if isinstance(class_derivs, dict):
        for cls_name, cls_def in class_derivs.items():
            if isinstance(cls_def, dict):
                visit(cls_name, cls_def, "", None)
    return findings


