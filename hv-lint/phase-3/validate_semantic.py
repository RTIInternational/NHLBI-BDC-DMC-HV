# UCUM <-> dbGaP informal unit equivalences.
# Keys: UCUM notation used in YAML source_unit.
# Values: set of equivalent dbGaP unit strings (case-insensitive match).
_UCUM_TO_DBGAP: dict[str, set[str]] = {
    "[lb_av]": {"lb", "lbs", "pounds", "pound"},
    "[in_us]": {"in", "inches", "inch"},
    "[in_i]":  {"in", "inches", "inch"},
    "kg":      {"kg", "kilograms", "kilogram"},
    "cm":      {"cm", "centimeters", "centimeter"},
    "m":       {"m", "meters", "meter"},
    "mm[Hg]":  {"mmhg", "mm hg", "mm(hg)"},
    "mg/dL":   {"mg/dl"},
    "g/dL":    {"g/dl"},
    "mg":      {"mg"},
    "g":       {"g", "gm", "grams", "gram"},
    "mL":      {"ml", "milliliters"},
    "L":       {"l", "liters", "liter"},
    "mm":      {"mm"},
    "%":       {"%", "percent"},
    "ms":      {"ms", "msec", "milliseconds"},
    "s":       {"seconds", "sec", "s"},
    "min":     {"min", "minutes"},
    "d":       {"days", "day", "d"},
    "a":       {"years", "year", "yr"},
    "mo":      {"months", "month"},
    "u[IU]/mL": {"uiu/ml", "uiu/ml", "iu/ml", "miu/ml"},
    "10*3/uL": {"10*3/ul", "1000/ul", "k/ul", "10^3/ul"},
}


def _units_compatible(ucum_unit: str, dbgap_unit: str) -> bool:
    """Check if a UCUM source_unit is compatible with a dbGaP declared unit.

    Returns True if they match (meaning the conversion IS consistent
    with the source unit), or if we can't determine compatibility.
    """
    if not ucum_unit or not dbgap_unit:
        return True  # Can't check -- don't flag

    ucum_clean = ucum_unit.strip().strip("'\"")
    dbgap_lower = dbgap_unit.strip().lower()

    # Direct match (case-insensitive)
    if ucum_clean.lower() == dbgap_lower:
        return True

    # Look up UCUM equivalences
    equivalents = _UCUM_TO_DBGAP.get(ucum_clean)
    if equivalents and dbgap_lower in equivalents:
        return True

    # Reverse check: if dbGaP unit matches the UCUM target_unit, that's
    # a MISMATCH (source is already in target units, conversion is wrong).
    # This case is handled by the caller checking source != dbgap.

    # If the UCUM unit is not in our map, we can't verify -- don't flag
    if ucum_clean not in _UCUM_TO_DBGAP:
        return True

    # UCUM is in our map but dbGaP unit doesn't match any equivalent
    return False


def _walk_slot_derivations(block: dict):
    """Yield (class_name, slot_name, slot_def, parent_pht) for all slot_derivations.

    Handles both top-level class_derivations and nested object_derivations
    (e.g., Quantity inside value_quantity).
    """
    class_derivs = block.get("class_derivations")
    if not isinstance(class_derivs, dict):
        return

    for cls_name, cls_def in class_derivs.items():
        if not isinstance(cls_def, dict):
            continue
        pht = cls_def.get("populated_from")
        slot_derivs = cls_def.get("slot_derivations")
        if isinstance(slot_derivs, dict):
            for slot_name, slot_def in slot_derivs.items():
                if isinstance(slot_def, dict):
                    yield cls_name, slot_name, slot_def, pht
                    # Check nested object_derivations (e.g., Quantity)
                    obj_derivs = slot_def.get("object_derivations")
                    if isinstance(obj_derivs, list):
                        for od in obj_derivs:
                            if not isinstance(od, dict):
                                continue
                            nested_cd = od.get("class_derivations")
                            if not isinstance(nested_cd, dict):
                                continue
                            for ncls, ncls_def in nested_cd.items():
                                if not isinstance(ncls_def, dict):
                                    continue
                                nested_pht = ncls_def.get("populated_from", pht)
                                nested_sd = ncls_def.get("slot_derivations")
                                if isinstance(nested_sd, dict):
                                    for ns_name, ns_def in nested_sd.items():
                                        if isinstance(ns_def, dict):
                                            yield ncls, ns_name, ns_def, nested_pht


def check_unit_conversion_mismatch(
    block: dict, block_idx: int, rel_path: str,
    detail_idx: DetailIndex,
) -> list[Finding]:
    """Check 3.14: unit_conversion source_unit vs dbGaP declared unit.

    When a slot has unit_conversion with source_unit, the declared
    source_unit should match what dbGaP says the variable's unit is.
    If dbGaP says the variable is already in the target unit, the
    conversion would corrupt the data (e.g., halving weights).
    """
    findings: list[Finding] = []

    for cls_name, slot_name, slot_def, parent_pht in _walk_slot_derivations(block):
        uc = slot_def.get("unit_conversion")
        if not isinstance(uc, dict):
            continue

        source_unit = uc.get("source_unit")
        target_unit = uc.get("target_unit")
        if not source_unit:
            continue

        # Find the PHV being converted
        phv = slot_def.get("populated_from")
        if not isinstance(phv, str) or not PHV_RE.fullmatch(phv):
            continue

        detail = detail_idx.records.get(phv)
        if not detail or not detail.unit:
            continue

        dbgap_unit = detail.unit

        # Check: does source_unit match what dbGaP declares?
        if not _units_compatible(source_unit, dbgap_unit):
            # Additional check: is dbGaP unit actually the TARGET unit?
            # This means source is already converted -- critical error.
            target_matches_dbgap = False
            if target_unit:
                target_clean = str(target_unit).strip().strip("'\"").lower()
                if target_clean == dbgap_unit.strip().lower():
                    target_matches_dbgap = True

            if target_matches_dbgap:
                severity = "CRITICAL"
                detail_msg = (
                    f"dbGaP declares unit='{dbgap_unit}' which matches "
                    f"target_unit='{target_unit}' -- source data is ALREADY "
                    f"in the target unit. This conversion will corrupt values"
                )
            else:
                severity = "ERROR"
                detail_msg = (
                    f"dbGaP declares unit='{dbgap_unit}' which does not "
                    f"match source_unit='{source_unit}'"
                )

            findings.append(Finding(
                file=rel_path,
                block=block_idx,
                check="3.14",
                severity=severity,
                message=(
                    f"{cls_name}.{slot_name}: {phv} ({detail.name}) "
                    f"has unit_conversion source_unit='{source_unit}' but "
                    f"{detail_msg}"
                ),
            ))

    return findings


# ---------------------------------------------------------------------------
# Check 3.13: Condition Null-Default Risk (Collection Interval)
# ---------------------------------------------------------------------------

# Matches "Collected in: P1 P2 P3" style values
_COLLECTED_IN_RE = re.compile(r"^Collected\s+in:\s*(.+)$", re.IGNORECASE)

# Sub-phase aliases: if a parent phase is in coll_interval, its sub-phases
# are considered covered.  COPDGene P3B is "Phase 3 Short-term 1-year
# follow-up" -- a sub-visit of P3 that dbGaP rolls into "Collected in: P3".
_PHASE_SUB_ALIASES: dict[str, str] = {
    "P3B": "P3",  # COPDGene Phase 3B -> Phase 3
}


def _expand_ci_phases(ci_phases: set[str]) -> set[str]:
    """Expand collection-interval phases to include known sub-phase aliases."""
    expanded = set(ci_phases)
    for child, parent in _PHASE_SUB_ALIASES.items():
        if parent in ci_phases:
            expanded.add(child)
    return expanded

# Detects case() in expressions
_CASE_RE = re.compile(r"\bcase\s*\(")

# Matches case result strings: , "RESULT") or , 'RESULT')
_CASE_RESULT_DQ = re.compile(r',\s*"([^"]+)"\s*\)')
_CASE_RESULT_SQ = re.compile(r",\s*'([^']+)'\s*\)")


def _parse_ci_phases(coll_interval: str | None) -> set[str] | None:
    """Parse structured coll_interval into phase tokens, or None."""
    if not coll_interval:
        return None
    m = _COLLECTED_IN_RE.match(coll_interval.strip())
    if not m:
        return None
    tokens = m.group(1).split()
    return set(tokens) if tokens else None


def _extract_case_phases(expr: str) -> set[str]:
    """Extract visit phase tokens from a case() expression's result strings.

    E.g., case((..., 'COPDGene P1'), (..., 'COPDGene P2')) -> {'P1', 'P2'}
    """
    labels = _CASE_RESULT_DQ.findall(expr) + _CASE_RESULT_SQ.findall(expr)
    phases: set[str] = set()
    for label in labels:
        parts = label.strip().split()
        if len(parts) >= 2:
            token = parts[-1]
            if token != "None":
                phases.add(token)
    return phases


def check_condition_null_default(
    block: dict, block_idx: int, rel_path: str,
    detail_idx: DetailIndex,
) -> list[Finding]:
    """Check 3.13: Condition null-default risk from collection interval mismatch.

    For Condition class blocks that use value_mappings on condition_status:
    if the associated_visit case expression routes to phases where the
    condition_status source PHV is NOT collected (per coll_interval), the
    pipeline will see null and may default to ABSENT -- producing false
    negatives that look like valid data.

    This is a CRITICAL severity finding because the output is actively
    misleading (plausible enum value from null input).
    """
    findings: list[Finding] = []
    class_derivs = block.get("class_derivations")
    if not isinstance(class_derivs, dict):
        return findings

    for cls_name, cls_def in class_derivs.items():
        if cls_name != "Condition" or not isinstance(cls_def, dict):
            continue

        slot_derivs = cls_def.get("slot_derivations")
        if not isinstance(slot_derivs, dict):
            continue

        # Must have a case()-based associated_visit
        visit_slot = slot_derivs.get("associated_visit", {})
        if not isinstance(visit_slot, dict):
            continue
        visit_expr = visit_slot.get("expr")
        if not visit_expr or not _CASE_RE.search(str(visit_expr)):
            continue

        # Extract the phases from the visit case expression
        case_phases = _extract_case_phases(str(visit_expr))
        if not case_phases:
            continue

        # Find the condition_status PHV
        status_slot = slot_derivs.get("condition_status", {})
        if not isinstance(status_slot, dict):
            continue

        # Needs value_mappings (the pattern where null -> ABSENT happens)
        if not status_slot.get("value_mappings"):
            continue

        pf = status_slot.get("populated_from")
        if not isinstance(pf, str) or not PHV_RE.fullmatch(pf):
            continue

        detail = detail_idx.records.get(pf)
        if not detail or not detail.coll_interval:
            continue

        ci_phases = _parse_ci_phases(detail.coll_interval)
        if ci_phases is None:
            continue

        # Expand ci_phases with known sub-phase aliases
        # (e.g., P3 covers P3B in COPDGene)
        ci_expanded = _expand_ci_phases(ci_phases)

        uncovered = case_phases - ci_expanded
        if not uncovered:
            continue

        uncovered_str = ", ".join(sorted(uncovered))
        covered_str = ", ".join(sorted(ci_phases))

        findings.append(Finding(
            file=rel_path,
            block=block_idx,
            check="3.13",
            severity="CRITICAL",
            message=(
                f"Condition.condition_status ({pf}, {detail.name}) "
                f"is only collected at [{covered_str}] but visit case "
                f"routes to [{uncovered_str}] -- null "
                f"condition_status may default to ABSENT, producing "
                f"false negatives"
            ),
        ))

    return findings


# ---------------------------------------------------------------------------
# Check 3.15: Phantom Code Detection
# ---------------------------------------------------------------------------


def check_phantom_codes(
    block: dict, block_idx: int, rel_path: str,
    detail_idx: DetailIndex,
) -> list[Finding]:
    """Check 3.15: Flag value_mappings keys that don't exist in dbGaP coded values.

    Inverse of rule 3.9. Rule 3.9 catches dbGaP codes MISSING from YAML;
    this rule catches YAML codes that don't exist in dbGaP -- indicating a
    typo, copy-paste from another cohort, or stale value from a version
    migration.
    """
    findings: list[Finding] = []
    class_derivs = block.get("class_derivations")
    if not isinstance(class_derivs, dict):
        return findings

    for cls_name, cls_def in class_derivs.items():
        if not isinstance(cls_def, dict):
            continue
        slot_derivs = cls_def.get("slot_derivations")
        if not isinstance(slot_derivs, dict):
            continue

        for slot_name, slot_def in slot_derivs.items():
            if not isinstance(slot_def, dict):
                continue

            vm = slot_def.get("value_mappings")
            if not isinstance(vm, dict) or not vm:
                continue

            # Skip if there's also an expr (expr may handle additional logic)
            if slot_def.get("expr"):
                continue

            # Determine source PHV
            pf = slot_def.get("populated_from")
            if not isinstance(pf, str) or not PHV_RE.fullmatch(pf):
                continue

            detail = detail_idx.records.get(pf)
            if not detail or not detail.codes:
                continue

            # Compare: YAML keys vs dbGaP codes
            dbgap_codes = set(detail.codes.keys())
            yaml_codes = set(str(k) for k in vm.keys())

            phantom = yaml_codes - dbgap_codes
            if not phantom:
                continue

            for code in sorted(phantom):
                sev = "ERROR" if slot_name in HIGH_IMPACT_SLOTS else "WARNING"
                findings.append(Finding(
                    file=rel_path,
                    block=block_idx,
                    check="3.15",
                    severity=sev,
                    message=(
                        f"value_mappings on {cls_name}.{slot_name} "
                        f"({pf}) has code '{code}' which does not exist "
                        f"in dbGaP coded values for {detail.name} -- "
                        f"possible typo or cross-cohort copy-paste error. "
                        f"Valid codes: {sorted(dbgap_codes)}"
                    ),
                ))

    return findings


# ---------------------------------------------------------------------------
# Check 3.16: Quantity Missing Unit
# ---------------------------------------------------------------------------


def check_quantity_missing_unit(
    block: dict, block_idx: int, rel_path: str,
) -> list[Finding]:
    """Check 3.16: Flag Quantity blocks with value_decimal/value_integer but no unit.

    Walks object_derivations looking for Quantity class definitions that
    contain a numeric value slot but lack a sibling 'unit' slot. A Quantity
    without a unit is semantically incomplete -- downstream consumers cannot
    interpret the numeric value.

    Also checks top-level class_derivations named 'Quantity'.
    """
    findings: list[Finding] = []

    def _check_quantity_slots(
        cls_name: str, cls_def: dict, parent_slot: str,
    ) -> None:
        """Check a single Quantity class definition for missing unit."""
        slot_derivs = cls_def.get("slot_derivations")
        if not isinstance(slot_derivs, dict):
            return

        has_numeric = any(
            s in slot_derivs for s in ("value_decimal", "value_integer")
        )
        has_unit = "unit" in slot_derivs

        if has_numeric and not has_unit:
            numeric_slot = (
                "value_decimal" if "value_decimal" in slot_derivs
                else "value_integer"
            )
            context = f" (in {parent_slot})" if parent_slot else ""
            findings.append(Finding(
                file=rel_path,
                block=block_idx,
                check="3.16",
                severity="WARNING",
                message=(
                    f"{cls_name}{context} has {numeric_slot} but no "
                    f"unit slot -- Quantity without unit is semantically "
                    f"incomplete"
                ),
            ))

    # Walk top-level class_derivations
    class_derivs = block.get("class_derivations")
    if not isinstance(class_derivs, dict):
        return findings

    for cls_name, cls_def in class_derivs.items():
        if not isinstance(cls_def, dict):
            continue

        # Check if this IS a Quantity class at top level
        if cls_name == "Quantity":
            _check_quantity_slots(cls_name, cls_def, "")

        # Walk slot_derivations looking for object_derivations with Quantity
        slot_derivs = cls_def.get("slot_derivations")
        if not isinstance(slot_derivs, dict):
            continue

        for slot_name, slot_def in slot_derivs.items():
            if not isinstance(slot_def, dict):
                continue
            obj_derivs = slot_def.get("object_derivations")
            if not isinstance(obj_derivs, list):
                continue
            for od in obj_derivs:
                if not isinstance(od, dict):
                    continue
                nested_cd = od.get("class_derivations")
                if not isinstance(nested_cd, dict):
                    continue
                for ncls_name, ncls_def in nested_cd.items():
                    if not isinstance(ncls_def, dict):
                        continue
                    if ncls_name == "Quantity":
                        _check_quantity_slots(
                            ncls_name, ncls_def,
                            f"{cls_name}.{slot_name}",
                        )

    return findings


